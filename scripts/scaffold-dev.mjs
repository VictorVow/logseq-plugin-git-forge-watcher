// Scaffolds ./dev/ as a runnable Vite project whose plugin id carries a `-dev`
// suffix, so `npm run dev` (HMR) can run while the marketplace release — which
// owns the base id — stays installed. `npm run dev` regenerates this and runs
// Vite from inside ./dev/.
//
// Why run Vite from ./dev/ instead of the project root: vite-plugin-logseq
// reads `logseq.id` from `process.cwd()/package.json` and bakes it into the
// served bundle's hot-reload call. cwd=./dev means it reads this -dev id. The
// same plugin only injects HMR into modules whose id starts with process.cwd(),
// hence `resolve.preserveSymlinks` below: it keeps the symlinked src/ module
// ids under ./dev so HMR still fires.

import {
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const devDir = join(root, 'dev')

const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
pkg.name = `${pkg.name}-dev`
pkg.logseq.id = `${pkg.logseq.id}-dev`
pkg.logseq.title = `(Dev) ${pkg.logseq.title}`

rmSync(devDir, { recursive: true, force: true })
mkdirSync(join(devDir, 'dist'), { recursive: true })

writeFileSync(join(devDir, 'package.json'), `${JSON.stringify(pkg, null, 2)}\n`)

writeFileSync(
  join(devDir, 'vite.config.ts'),
  `import { defineConfig } from 'vite'
import logseqDevPlugin from 'vite-plugin-logseq'

// Generated by scripts/scaffold-dev.mjs — do not edit. preserveSymlinks keeps
// the symlinked src/ module ids under ./dev so vite-plugin-logseq injects HMR.
export default defineConfig({
  plugins: [logseqDevPlugin()],
  resolve: { preserveSymlinks: true },
})
`,
)

// Symlink the real sources so edits to ./src hot-reload the dev plugin.
symlinkSync(join(root, 'src'), join(devDir, 'src'), 'dir')
symlinkSync(join(root, 'index.html'), join(devDir, 'index.html'))

const icon = 'icon.png'
if (existsSync(join(root, icon))) {
  symlinkSync(join(root, icon), join(devDir, icon))
}

console.log(
  `Scaffolded ./dev/ for plugin id "${pkg.logseq.id}". ` +
    'In Logseq: Settings -> Plugins -> Load unpacked plugin -> select ./dev/ (once).',
)
